#!/bin/bash
set -e

# =============================================================================
# UsageFlow EC2 Bootstrap Script
# Installs Docker, Docker Compose, and configures the application
# =============================================================================

exec > >(tee /var/log/user-data.log) 2>&1
echo "Starting UsageFlow setup at $(date)"

# Variables from Terraform
PROJECT_NAME="${project_name}"
ENVIRONMENT="${environment}"
DB_HOST="${db_host}"
DB_PORT="${db_port}"
DB_NAME="${db_name}"
DB_USERNAME="${db_username}"
DB_PASSWORD="${db_password}"
JWT_SECRET="${jwt_secret}"
INTERNAL_API_KEY="${internal_api_key}"
DOMAIN_NAME="${domain_name}"

# =============================================================================
# SYSTEM UPDATES
# =============================================================================
echo "Updating system packages..."
apt-get update -y
apt-get upgrade -y

# =============================================================================
# INSTALL DOCKER
# =============================================================================
echo "Installing Docker..."

# Install prerequisites
apt-get install -y \
    apt-transport-https \
    ca-certificates \
    curl \
    gnupg \
    lsb-release \
    git \
    htop \
    jq

# Add Docker's official GPG key
curl -fsSL https://download.docker.com/linux/ubuntu/gpg | gpg --dearmor -o /usr/share/keyrings/docker-archive-keyring.gpg

# Set up the Docker repository
echo \
  "deb [arch=$(dpkg --print-architecture) signed-by=/usr/share/keyrings/docker-archive-keyring.gpg] https://download.docker.com/linux/ubuntu \
  $(lsb_release -cs) stable" | tee /etc/apt/sources.list.d/docker.list > /dev/null

# Install Docker Engine
apt-get update -y
apt-get install -y docker-ce docker-ce-cli containerd.io docker-compose-plugin

# Start and enable Docker
systemctl start docker
systemctl enable docker

# Add ubuntu user to docker group
usermod -aG docker ubuntu

# =============================================================================
# INSTALL DOCKER COMPOSE (standalone)
# =============================================================================
echo "Installing Docker Compose..."
curl -L "https://github.com/docker/compose/releases/latest/download/docker-compose-$(uname -s)-$(uname -m)" -o /usr/local/bin/docker-compose
chmod +x /usr/local/bin/docker-compose

# =============================================================================
# CREATE APPLICATION DIRECTORY
# =============================================================================
echo "Creating application directory..."
mkdir -p /opt/usageflow
cd /opt/usageflow

# =============================================================================
# CREATE ENVIRONMENT FILE
# =============================================================================
echo "Creating environment file..."
cat > /opt/usageflow/.env <<EOF
# UsageFlow Environment Configuration
# Generated by Terraform at $(date)

# Environment
ENVIRONMENT=$ENVIRONMENT
DEBUG=false

# Database (RDS)
POSTGRES_USER=$DB_USERNAME
POSTGRES_PASSWORD=$DB_PASSWORD
POSTGRES_DB=$DB_NAME
DATABASE_URL=postgresql+asyncpg://$DB_USERNAME:$DB_PASSWORD@$DB_HOST:$DB_PORT/$DB_NAME
SYNC_DATABASE_URL=postgresql://$DB_USERNAME:$DB_PASSWORD@$DB_HOST:$DB_PORT/$DB_NAME

# Authentication
JWT_SECRET_KEY=$JWT_SECRET
JWT_ALGORITHM=HS256
ACCESS_TOKEN_EXPIRE_MINUTES=30

# Internal API
USAGEFLOW_INTERNAL_API_KEY=$INTERNAL_API_KEY

# LiteLLM (set these manually after deployment)
LITELLM_MASTER_KEY=sk-change-me-in-production
LITELLM_SALT_KEY=sk-salt-change-me
OPENAI_API_KEY=
ANTHROPIC_API_KEY=

# Stripe (set these manually)
STRIPE_SECRET_KEY=
STRIPE_WEBHOOK_SECRET=

# Workers
API_WORKERS=2

# Domain
DOMAIN_NAME=$DOMAIN_NAME
FRONTEND_URL=http://localhost:3000
EOF

# Secure the env file
chmod 600 /opt/usageflow/.env
chown ubuntu:ubuntu /opt/usageflow/.env

# =============================================================================
# CREATE DOCKER COMPOSE FILE (Simplified for EC2 with RDS)
# =============================================================================
echo "Creating Docker Compose configuration..."
cat > /opt/usageflow/docker-compose.yml <<'COMPOSE_EOF'
version: '3.9'

services:
  # Redis Cache (runs locally on EC2)
  redis:
    image: redis:7-alpine
    container_name: usageflow-redis
    restart: always
    command: >
      redis-server
      --appendonly yes
      --maxmemory 256mb
      --maxmemory-policy allkeys-lru
    volumes:
      - redis_data:/data
    networks:
      - usageflow-network
    healthcheck:
      test: ["CMD", "redis-cli", "ping"]
      interval: 10s
      timeout: 5s
      retries: 5

  # FastAPI Backend
  api:
    image: ghcr.io/your-org/usageflow-api:latest
    build:
      context: ./backend
      dockerfile: Dockerfile
    container_name: usageflow-api
    restart: always
    command: >
      gunicorn app.main:app
      --workers ${API_WORKERS:-2}
      --worker-class uvicorn.workers.UvicornWorker
      --bind 0.0.0.0:8000
      --timeout 120
      --keep-alive 5
      --max-requests 10000
      --max-requests-jitter 1000
    ports:
      - "8000:8000"
    environment:
      - DATABASE_URL=${DATABASE_URL}
      - SYNC_DATABASE_URL=${SYNC_DATABASE_URL}
      - REDIS_URL=redis://redis:6379/0
      - JWT_SECRET_KEY=${JWT_SECRET_KEY}
      - JWT_ALGORITHM=${JWT_ALGORITHM:-HS256}
      - ACCESS_TOKEN_EXPIRE_MINUTES=${ACCESS_TOKEN_EXPIRE_MINUTES:-30}
      - ENVIRONMENT=${ENVIRONMENT:-production}
      - DEBUG=false
      - LITELLM_PROXY_URL=http://litellm:4000
      - USAGEFLOW_INTERNAL_API_KEY=${USAGEFLOW_INTERNAL_API_KEY}
      - STRIPE_SECRET_KEY=${STRIPE_SECRET_KEY}
      - STRIPE_WEBHOOK_SECRET=${STRIPE_WEBHOOK_SECRET}
    depends_on:
      redis:
        condition: service_healthy
    healthcheck:
      test: ["CMD", "curl", "-f", "http://localhost:8000/health"]
      interval: 30s
      timeout: 10s
      retries: 3
      start_period: 40s
    networks:
      - usageflow-network

  # LiteLLM Proxy
  litellm:
    image: ghcr.io/berriai/litellm:main-latest
    container_name: usageflow-litellm
    restart: always
    ports:
      - "4000:4000"
    environment:
      - LITELLM_MASTER_KEY=${LITELLM_MASTER_KEY}
      - OPENAI_API_KEY=${OPENAI_API_KEY}
      - ANTHROPIC_API_KEY=${ANTHROPIC_API_KEY}
      - DATABASE_URL=${SYNC_DATABASE_URL}
      - REDIS_HOST=redis
      - REDIS_PORT=6379
    depends_on:
      redis:
        condition: service_healthy
    healthcheck:
      test: ["CMD", "curl", "-f", "http://localhost:4000/health"]
      interval: 30s
      timeout: 10s
      retries: 3
      start_period: 60s
    networks:
      - usageflow-network

  # Nginx Reverse Proxy
  nginx:
    image: nginx:alpine
    container_name: usageflow-nginx
    restart: always
    ports:
      - "80:80"
      - "443:443"
    volumes:
      - ./nginx/default.conf:/etc/nginx/conf.d/default.conf:ro
      - ./frontend/dist:/usr/share/nginx/html:ro
      - ./certbot/conf:/etc/letsencrypt:ro
      - ./certbot/www:/var/www/certbot:ro
    depends_on:
      - api
    networks:
      - usageflow-network

volumes:
  redis_data:

networks:
  usageflow-network:
    driver: bridge
COMPOSE_EOF

# =============================================================================
# CREATE NGINX CONFIG
# =============================================================================
echo "Creating Nginx configuration..."
mkdir -p /opt/usageflow/nginx
cat > /opt/usageflow/nginx/default.conf <<'NGINX_EOF'
upstream api {
    server api:8000;
    keepalive 32;
}

upstream litellm {
    server litellm:4000;
    keepalive 16;
}

server {
    listen 80;
    server_name _;

    # Security headers
    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header X-XSS-Protection "1; mode=block" always;

    # Frontend
    location / {
        root /usr/share/nginx/html;
        try_files $uri $uri/ /index.html;
    }

    # API
    location /api/ {
        proxy_pass http://api;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header Connection "";
        proxy_connect_timeout 60s;
        proxy_send_timeout 60s;
        proxy_read_timeout 120s;
    }

    # Health check
    location /health {
        proxy_pass http://api/health;
        proxy_http_version 1.1;
        access_log off;
    }

    # LiteLLM
    location /llm/ {
        rewrite ^/llm/(.*) /$1 break;
        proxy_pass http://litellm;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header Connection "";
        proxy_read_timeout 300s;
        proxy_buffering off;
    }

    # Docs
    location /docs {
        proxy_pass http://api/docs;
        proxy_http_version 1.1;
    }

    location /redoc {
        proxy_pass http://api/redoc;
        proxy_http_version 1.1;
    }

    location /openapi.json {
        proxy_pass http://api/openapi.json;
        proxy_http_version 1.1;
    }
}
NGINX_EOF

# =============================================================================
# CREATE DIRECTORIES
# =============================================================================
mkdir -p /opt/usageflow/frontend/dist
mkdir -p /opt/usageflow/certbot/conf
mkdir -p /opt/usageflow/certbot/www
mkdir -p /opt/usageflow/backend

# Create placeholder index.html
cat > /opt/usageflow/frontend/dist/index.html <<'HTML_EOF'
<!DOCTYPE html>
<html>
<head>
    <title>UsageFlow - Coming Soon</title>
    <style>
        body { font-family: -apple-system, BlinkMacSystemFont, sans-serif; background: #0a0a0f; color: white; display: flex; align-items: center; justify-content: center; height: 100vh; margin: 0; }
        .container { text-align: center; }
        h1 { font-size: 3em; margin-bottom: 0.5em; background: linear-gradient(to right, #6366f1, #a855f7, #ec4899); -webkit-background-clip: text; -webkit-text-fill-color: transparent; }
        p { color: #9ca3af; font-size: 1.2em; }
    </style>
</head>
<body>
    <div class="container">
        <h1>UsageFlow</h1>
        <p>Application is being deployed. Check back soon!</p>
    </div>
</body>
</html>
HTML_EOF

# =============================================================================
# SET PERMISSIONS
# =============================================================================
chown -R ubuntu:ubuntu /opt/usageflow

# =============================================================================
# CREATE SYSTEMD SERVICE
# =============================================================================
echo "Creating systemd service..."
cat > /etc/systemd/system/usageflow.service <<'SERVICE_EOF'
[Unit]
Description=UsageFlow Application
Requires=docker.service
After=docker.service

[Service]
Type=oneshot
RemainAfterExit=yes
WorkingDirectory=/opt/usageflow
ExecStart=/usr/local/bin/docker-compose up -d
ExecStop=/usr/local/bin/docker-compose down
User=ubuntu
Group=docker

[Install]
WantedBy=multi-user.target
SERVICE_EOF

# Enable the service (but don't start yet - need to clone repo first)
systemctl daemon-reload
systemctl enable usageflow.service

# =============================================================================
# CREATE DEPLOYMENT SCRIPT
# =============================================================================
echo "Creating deployment script..."
cat > /opt/usageflow/deploy.sh <<'DEPLOY_EOF'
#!/bin/bash
set -e

cd /opt/usageflow

echo "Pulling latest code..."
# git pull origin main  # Uncomment after setting up git

echo "Building containers..."
docker-compose build

echo "Running database migrations..."
docker-compose run --rm api alembic upgrade head

echo "Restarting services..."
docker-compose down
docker-compose up -d

echo "Deployment complete!"
docker-compose ps
DEPLOY_EOF

chmod +x /opt/usageflow/deploy.sh
chown ubuntu:ubuntu /opt/usageflow/deploy.sh

# =============================================================================
# INSTALL CERTBOT (for SSL)
# =============================================================================
echo "Installing Certbot..."
snap install core
snap refresh core
snap install --classic certbot
ln -sf /snap/bin/certbot /usr/bin/certbot

# =============================================================================
# CONFIGURE SWAP (for t3.micro/small instances)
# =============================================================================
echo "Configuring swap..."
if [ ! -f /swapfile ]; then
    fallocate -l 2G /swapfile
    chmod 600 /swapfile
    mkswap /swapfile
    swapon /swapfile
    echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

# =============================================================================
# CONFIGURE SYSTEM LIMITS
# =============================================================================
echo "Configuring system limits..."
cat >> /etc/security/limits.conf <<LIMITS_EOF
* soft nofile 65535
* hard nofile 65535
ubuntu soft nofile 65535
ubuntu hard nofile 65535
LIMITS_EOF

# =============================================================================
# DONE
# =============================================================================
echo "=============================================="
echo "UsageFlow setup complete at $(date)"
echo "=============================================="
echo ""
echo "Next steps:"
echo "1. SSH into the instance"
echo "2. Clone your repository to /opt/usageflow"
echo "3. Update /opt/usageflow/.env with API keys"
echo "4. Run: cd /opt/usageflow && ./deploy.sh"
echo ""
echo "Or start with the placeholder:"
echo "  sudo systemctl start usageflow"
echo ""
